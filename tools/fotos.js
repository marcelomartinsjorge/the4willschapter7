// Fotos de conferência: abre telas-chave e salva PNG (uso: node tools/fotos.js <porta> <pasta> [mobile])
const { chromium } = require('playwright');
(async () => {
  const porta = process.argv[2] || 8737, out = process.argv[3] || '/tmp', mob = process.argv[4] === 'mobile';
  const browser = await chromium.launch();
  const page = await browser.newPage(mob ? { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true } : { viewport: { width: 1280, height: 800 } });
  const erros = []; page.on('pageerror', (e) => erros.push(e.message));
  await page.addInitScript(() => { localStorage.clear(); localStorage.setItem('livro_lang', 'pt'); window.__LEITURA_K = .2; });
  await page.goto(`http://localhost:${porta}/index.html`);
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${out}/00-capa.png` });
  await page.click('#cvGo'); await page.waitForTimeout(700); await page.evaluate(() => document.getElementById('intertitulo').click());
  const ir = async (id, ms = 1800) => { await page.evaluate((id) => window.__LIVRO.ir(id), id); await page.waitForTimeout(ms); };
  const foto = async (n) => { await page.screenshot({ path: `${out}/${n}.png` }); };
  const portoes = async () => { for (let i = 0; i < 6; i++) { const ok = await page.evaluate(() => { const b = document.querySelector('.portao-btn'); if (b) { b.click(); return true; } return false; }); if (!ok) break; await page.waitForTimeout(400); } };
  const joga = async () => { await portoes(); await page.waitForTimeout(400); await page.click('#mgGo').catch(() => {}); };
  await ir('a01', 4200); await foto('01-a01-frase');
  await page.evaluate(() => { const L = window.__LIVRO; ['velha', 'sarnai', 'ossian', 'ruo', 'iska'].forEach((g) => L.guarda(g)); });
  await page.waitForTimeout(900); await foto('02-cartoes');
  await page.click('#veu'); await page.waitForTimeout(600); await foto('03-colecao'); await page.click('#clClose');
  await ir('a06', 2500); await page.evaluate(() => window.__LIVRO.frase('mostra', 'laura')); await page.waitForTimeout(2000); await foto('04-a06-moeda');
  await ir('a09'); await joga(); await page.waitForTimeout(900);
  await page.click('.es-c').catch(() => {}); await page.waitForTimeout(1500); await foto('05-escuta');
  await page.evaluate(() => { document.getElementById('mg').className = ''; document.body.classList.remove('mg-on'); });
  await ir('a10', 6500); await foto('06-piscar');
  await page.waitForTimeout(2500);
  await ir('b03'); await joga(); await page.waitForTimeout(2500); await foto('07-mao');
  await page.evaluate(() => { document.getElementById('mg').className = ''; document.body.classList.remove('mg-on'); });
  await ir('b05'); await joga(); await page.waitForTimeout(19000); await foto('08-morta');
  await page.evaluate(() => { document.getElementById('mg').className = ''; document.body.classList.remove('mg-on'); });
  await page.evaluate(() => { const L = window.__LIVRO; L.guarda('sargento'); L.guarda('hobb'); });
  await ir('c04'); await joga(); await page.waitForTimeout(2200);
  await page.click('.az-op').catch(() => {}); await page.waitForTimeout(3500); await foto('09-lamina');
  await page.evaluate(() => { document.getElementById('mg').className = ''; document.body.classList.remove('mg-on'); });
  await page.evaluate(() => { const s = window.__LIVRO.st; s.escolhas.alvo1 = 'joseph'; s.escolhas.masc1 = 'vinho'; s.colecao.push('vinho'); });
  await ir('n1j'); await joga(); await page.waitForTimeout(2200);
  await page.click('.az-op').catch(() => {}); await page.waitForTimeout(5200); await foto('10-anzol');
  await page.evaluate(() => { document.getElementById('mg').className = ''; document.body.classList.remove('mg-on'); });
  await page.evaluate(() => { const s = window.__LIVRO.st; s.escolhas.alvo2 = 'mapas'; });
  await ir('n2o'); await page.click('#mgGo').catch(() => {}); await page.waitForTimeout(1200); await foto('11-ordem');
  await page.evaluate(() => { document.getElementById('mg').className = ''; document.body.classList.remove('mg-on'); });
  await ir('e05', 5000); await foto('12-fim');
  console.log('erros', erros);
  await browser.close();
})();
